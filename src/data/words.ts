// Helper to pick a random word avoiding recently used words
export function getRandomWord(recentWords: string[] = []): string {
  if (WORDS.length === 0) return "Resilience";

  // Filter out recent words if we have enough remaining words
  const availableWords = WORDS.filter(
    (w) => !recentWords.includes(w)
  );

  const pool = availableWords.length > 0 ? availableWords : WORDS;
  const randomIndex = Math.floor(Math.random() * pool.length);
  return pool[randomIndex];
}
